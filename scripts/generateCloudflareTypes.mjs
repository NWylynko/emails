/**
 * Generates the TypeScript types for the Worker environment.
 *
 * Three problems this works around:
 *
 * 1. `wrangler types` in one shot emits runtime globals AND the Env interface
 *    into a single file, and that file declares
 *    `Cloudflare.GlobalProps.mainModule` as `typeof import("./worker")`, which
 *    drags `worker.ts` into the Next app's TypeScript program no matter what
 *    `tsconfig.json`'s `exclude` says. `worker.ts` imports
 *    `./.open-next/worker.js`, which does not exist before a build, so a clean
 *    checkout could never typecheck. Generate the halves separately and strip
 *    that block.
 *
 * 2. `wrangler types` learns var names from `.dev.vars`. There is no such file
 *    here by design — values live in Infisical — so it would emit an env
 *    containing only bindings, and every `env.CLERK_SECRET_KEY` would fail to
 *    typecheck. The names therefore come from `.env.schema`, which is the
 *    committed source of truth for them anyway.
 *
 * 3. Runtime globals override the DOM lib, so `Response.json()` returns
 *    `unknown` rather than `any` in client components. That is correct, just
 *    surprising.
 *
 * Run via `pnpm cf-typegen` after changing wrangler.jsonc or .env.schema.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const ENV_TYPES = "cloudflare-env.d.ts";
const RUNTIME_TYPES = "worker-runtime.d.ts";
const SCHEMA_VAR_TYPES = "worker-env-vars.d.ts";

/** Local tooling only — never read off the Worker's `env`. */
const NOT_ON_THE_WORKER = new Set([
  "CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_HYPERDRIVE",
]);

function wranglerTypes(args) {
  execFileSync(
    "wrangler",
    ["types", "--env-interface", "CloudflareEnv", ...args],
    { stdio: "inherit" }
  );
}

wranglerTypes(["--include-runtime=false", ENV_TYPES]);
wranglerTypes(["--include-env=false", RUNTIME_TYPES]);

const source = readFileSync(ENV_TYPES, "utf8");
const withoutGlobalProps = source.replace(
  /\tinterface GlobalProps \{\n\t\tmainModule: typeof import\("[^"]*"\);\n\t\}\n/,
  ""
);

if (withoutGlobalProps === source) {
  console.warn(
    `generateCloudflareTypes: GlobalProps block not found in ${ENV_TYPES} — ` +
      `wrangler's output shape may have changed. Check that worker.ts is still ` +
      `excluded from the app's TypeScript program.`
  );
}

writeFileSync(ENV_TYPES, withoutGlobalProps);

// Declaration merging: cloudflare-env.d.ts declares `interface CloudflareEnv`
// globally, so this second global declaration adds to it rather than replacing.
const names = readFileSync(".env.schema", "utf8")
  .split("\n")
  .map((line) => line.match(/^([A-Z][A-Z0-9_]*)=/)?.[1])
  .filter((name) => name && !NOT_ON_THE_WORKER.has(name));

writeFileSync(
  SCHEMA_VAR_TYPES,
  `// Generated by scripts/generateCloudflareTypes.mjs from .env.schema.\n` +
    `// Values come from Infisical: the dev environment via scripts/devWorker.sh,\n` +
    `// production via the Infisical -> Cloudflare Workers secret sync.\n` +
    `interface CloudflareEnv {\n` +
    names.map((name) => `\t${name}: string;`).join("\n") +
    `\n}\n`
);

console.log(
  `generateCloudflareTypes: wrote ${ENV_TYPES}, ${RUNTIME_TYPES} and ` +
    `${SCHEMA_VAR_TYPES} (${names.length} vars from .env.schema)`
);
