-- Baseline. This migration describes the schema as it already existed on the
-- production and dev databases when drizzle-kit was introduced, so it is written
-- to be idempotent: every statement is a no-op against a database that already
-- has these tables, and creates them correctly against an empty one.
--
-- That is deliberate, and it does two jobs at once:
--   1. It lets `drizzle-kit migrate` run against the live databases without
--      failing on "relation already exists", so they can be brought under
--      migration control without hand-inserting rows into
--      drizzle.__drizzle_migrations.
--   2. It makes a blank database reproducible. Recreating the dev clone used to
--      mean branching from production because nothing in the repo could build
--      the schema from scratch; now `pnpm db:migrate` can.
--
-- Generated by drizzle-kit, then edited for idempotency. The accompanying
-- meta/0000_snapshot.json is drizzle-kit's own state model and is NOT affected
-- by these edits, so future `drizzle-kit generate` diffs stay correct.

